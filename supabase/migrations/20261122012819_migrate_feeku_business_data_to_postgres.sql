CREATE OR REPLACE FUNCTION public.restore_feeku_user_backup(p_data jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF auth.uid() IS NULL OR auth.role() <> 'authenticated' THEN
    RAISE EXCEPTION 'Authentication is required' USING ERRCODE = '42501';
  END IF;
  RETURN private.replace_feeku_business_data(auth.uid(),p_data,true);
END;
$function$;
REVOKE ALL ON FUNCTION public.restore_feeku_user_backup(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.restore_feeku_user_backup(jsonb) TO authenticated;

CREATE OR REPLACE FUNCTION public.import_feeku_legacy_user(p_user_id uuid,p_data jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_existing jsonb;
  v_counts jsonb;
BEGIN
  IF auth.role() <> 'service_role' THEN
    RAISE EXCEPTION 'Only trusted server tooling may import legacy data' USING ERRCODE = '42501';
  END IF;
  SELECT counts INTO v_existing
    FROM private.feeku_legacy_import_runs
   WHERE user_id = p_user_id;
  IF FOUND THEN
    RETURN coalesce(v_existing,'{}'::jsonb) || jsonb_build_object('already_imported',true);
  END IF;
  v_counts := private.replace_feeku_business_data(p_user_id,p_data,false);
  INSERT INTO private.feeku_legacy_import_runs(user_id,counts)
  VALUES(p_user_id,v_counts);
  RETURN v_counts || jsonb_build_object('already_imported',false);
END;
$function$;
REVOKE ALL ON FUNCTION public.import_feeku_legacy_user(uuid,jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.import_feeku_legacy_user(uuid,jsonb) TO service_role;

