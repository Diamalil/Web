-- Transaction save RPC: all line inserts, stock movements and margin updates run in one DB transaction.
CREATE OR REPLACE FUNCTION public.save_feeku_transaction(
  p_legacy_id bigint,
  p_entry_date date,
  p_description text,
  p_direction public.transaction_direction,
  p_amount numeric,
  p_items jsonb DEFAULT '[]'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path TO ''
AS $function$
DECLARE
  v_user_id uuid := auth.uid();
  v_transaction_id uuid;
  v_legacy_id bigint;
  v_description text := left(btrim(coalesce(p_description, '')), 200);
  v_amount numeric(18,2) := 0;
  v_source public.transaction_source;
  v_item jsonb;
  v_product_id uuid;
  v_product record;
  v_product_legacy_id bigint;
  v_quantity numeric(18,3);
  v_sale_price numeric(18,2);
  v_cost numeric(18,2);
  v_name text;
  v_sku text;
  v_count integer := 0;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication is required' USING ERRCODE = '42501';
  END IF;
  IF p_entry_date IS NULL OR v_description = '' THEN
    RAISE EXCEPTION 'Tanggal dan keterangan wajib diisi' USING ERRCODE = '22023';
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' THEN
    RAISE EXCEPTION 'Rincian transaksi harus berupa array' USING ERRCODE = '22023';
  END IF;
  v_count := jsonb_array_length(p_items);
  IF v_count > 50 THEN
    RAISE EXCEPTION 'Maksimal 50 baris produk dalam satu transaksi' USING ERRCODE = '22023';
  END IF;

  v_source := CASE WHEN v_count > 0 THEN 'catalog_sale'::public.transaction_source
                   ELSE 'manual'::public.transaction_source END;
  IF v_count > 0 AND p_direction <> 'Masuk' THEN
    RAISE EXCEPTION 'Produk katalog hanya bisa digunakan untuk transaksi Masuk' USING ERRCODE = '22023';
  END IF;

  IF v_count = 0 THEN
    IF p_amount IS NULL OR p_amount <= 0 OR p_amount > 1000000000000 THEN
      RAISE EXCEPTION 'Nominal transaksi tidak valid' USING ERRCODE = '22023';
    END IF;
    v_amount := round(p_amount, 2);
  ELSE
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
      v_quantity := nullif(v_item->>'quantity','')::numeric;
      IF v_quantity IS NULL OR v_quantity <= 0 OR v_quantity > 1000000 THEN
        RAISE EXCEPTION 'Jumlah produk tidak valid' USING ERRCODE = '22023';
      END IF;
      v_product_legacy_id := nullif(v_item->>'productLegacyId','')::bigint;
      IF v_product_legacy_id IS NOT NULL THEN
        SELECT id, name, sku, unit_cost, sale_price, stock_quantity, reserved_quantity
          INTO v_product
          FROM public.products
         WHERE user_id = v_user_id AND legacy_id = v_product_legacy_id AND is_active = true
         FOR UPDATE;
        IF NOT FOUND THEN
          RAISE EXCEPTION 'Produk tidak ditemukan pada katalog akun ini' USING ERRCODE = 'P0002';
        END IF;
        IF v_product.unit_cost <= 0 THEN
          RAISE EXCEPTION 'Isi HPP/modal per unit untuk produk "%" sebelum dijual', v_product.name USING ERRCODE = '22023';
        END IF;
        v_sale_price := coalesce(nullif(v_item->>'unitSalePrice','')::numeric, v_product.sale_price);
        v_cost := v_product.unit_cost;
        v_name := v_product.name;
        v_sku := v_product.sku;
      ELSE
        v_name := left(btrim(coalesce(v_item->>'productName','')),150);
        IF v_name = '' THEN
          RAISE EXCEPTION 'Nama snapshot produk wajib diisi' USING ERRCODE = '22023';
        END IF;
        v_sale_price := nullif(v_item->>'unitSalePrice','')::numeric;
        v_cost := coalesce(nullif(v_item->>'unitCost','')::numeric,0);
        v_sku := nullif(v_item->>'sku','');
      END IF;
      IF v_sale_price IS NULL OR v_sale_price <= 0 OR v_sale_price > 1000000000000
         OR v_cost < 0 OR v_cost > 1000000000000 THEN
        RAISE EXCEPTION 'HPP atau harga jual snapshot tidak valid' USING ERRCODE = '22023';
      END IF;
      v_amount := v_amount + round(v_quantity * v_sale_price, 2);
      IF v_amount > 1000000000000 THEN
        RAISE EXCEPTION 'Total penjualan melebihi batas' USING ERRCODE = '22023';
      END IF;
    END LOOP;
  END IF;

  IF p_legacy_id IS NULL THEN
    INSERT INTO public.transactions(user_id, entry_date, description, direction, amount, source)
    VALUES (v_user_id, p_entry_date, v_description, p_direction, v_amount, v_source)
    RETURNING id, legacy_id INTO v_transaction_id, v_legacy_id;
  ELSE
    SELECT id INTO v_transaction_id
      FROM public.transactions
     WHERE user_id = v_user_id AND legacy_id = p_legacy_id
     FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Transaksi tidak ditemukan' USING ERRCODE = 'P0002';
    END IF;
    DELETE FROM public.transaction_items
     WHERE user_id = v_user_id AND transaction_id = v_transaction_id;
    UPDATE public.transactions
       SET entry_date = p_entry_date, description = v_description,
           direction = p_direction, amount = v_amount, source = v_source
     WHERE id = v_transaction_id AND user_id = v_user_id
     RETURNING legacy_id INTO v_legacy_id;
  END IF;

  IF v_count > 0 THEN
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
      v_quantity := (v_item->>'quantity')::numeric;
      v_product_legacy_id := nullif(v_item->>'productLegacyId','')::bigint;
      v_product_id := NULL;
      IF v_product_legacy_id IS NOT NULL THEN
        SELECT id, name, sku, unit_cost, sale_price
          INTO v_product
          FROM public.products
         WHERE user_id = v_user_id AND legacy_id = v_product_legacy_id AND is_active = true;
        v_product_id := v_product.id;
        v_name := v_product.name;
        v_sku := v_product.sku;
        v_cost := v_product.unit_cost;
        v_sale_price := coalesce(nullif(v_item->>'unitSalePrice','')::numeric, v_product.sale_price);
      ELSE
        v_name := left(btrim(coalesce(v_item->>'productName','')),150);
        v_sku := nullif(v_item->>'sku','');
        v_cost := coalesce(nullif(v_item->>'unitCost','')::numeric,0);
        v_sale_price := nullif(v_item->>'unitSalePrice','')::numeric;
      END IF;
      INSERT INTO public.transaction_items(
        user_id, transaction_id, product_id, product_name_snapshot, sku_snapshot,
        quantity, unit_cost_snapshot, sale_price_snapshot
      ) VALUES (
        v_user_id, v_transaction_id, v_product_id, v_name, v_sku,
        v_quantity, v_cost, v_sale_price
      );
    END LOOP;
  END IF;

  SELECT amount INTO v_amount FROM public.transactions
   WHERE id = v_transaction_id AND user_id = v_user_id;
  RETURN jsonb_build_object('id', v_legacy_id, 'uuid', v_transaction_id, 'amount', v_amount);
END;
$function$;

GRANT EXECUTE ON FUNCTION public.save_feeku_transaction(bigint,date,text,public.transaction_direction,numeric,jsonb) TO authenticated;

CREATE OR REPLACE FUNCTION public.adjust_feeku_stock(p_product_legacy_id bigint, p_delta numeric)
RETURNS TABLE(id bigint, name text, stock numeric)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path TO ''
AS $function$
BEGIN
  IF auth.uid() IS NULL OR p_delta NOT IN (-1,1) THEN
    RAISE EXCEPTION 'Perubahan stok tidak valid' USING ERRCODE = '22023';
  END IF;
  RETURN QUERY
  UPDATE public.products p
     SET stock_quantity = p.stock_quantity + p_delta,
         updated_at = now()
   WHERE p.user_id = auth.uid()
     AND p.legacy_id = p_product_legacy_id
     AND p.stock_quantity + p_delta >= p.reserved_quantity
  RETURNING p.legacy_id, p.name, p.stock_quantity;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Barang tidak ditemukan atau stok tidak boleh kurang dari stok yang dicadangkan' USING ERRCODE = 'P0002';
  END IF;
END;
$function$;
GRANT EXECUTE ON FUNCTION public.adjust_feeku_stock(bigint,numeric) TO authenticated;

