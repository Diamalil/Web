-- Stock triggers now tolerate a deleted catalog product while retaining the sale snapshot.
CREATE OR REPLACE FUNCTION private.apply_transaction_item_stock()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO ''
AS $function$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.product_id IS NULL THEN
      RETURN NEW;
    END IF;
    UPDATE public.products
       SET stock_quantity = stock_quantity - NEW.quantity,
           updated_at = now()
     WHERE id = NEW.product_id
       AND user_id = NEW.user_id
       AND stock_quantity - reserved_quantity >= NEW.quantity;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Insufficient available stock for product %', NEW.product_id
        USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    IF OLD.product_id IS NOT NULL THEN
      UPDATE public.products
         SET stock_quantity = stock_quantity + OLD.quantity,
             updated_at = now()
       WHERE id = OLD.product_id AND user_id = OLD.user_id;
    END IF;
    IF NEW.product_id IS NOT NULL THEN
      UPDATE public.products
         SET stock_quantity = stock_quantity - NEW.quantity,
             updated_at = now()
       WHERE id = NEW.product_id
         AND user_id = NEW.user_id
         AND stock_quantity - reserved_quantity >= NEW.quantity;
      IF NOT FOUND THEN
        RAISE EXCEPTION 'Insufficient available stock for product %', NEW.product_id
          USING ERRCODE = '23514';
      END IF;
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    IF OLD.product_id IS NOT NULL THEN
      UPDATE public.products
         SET stock_quantity = stock_quantity + OLD.quantity,
             updated_at = now()
       WHERE id = OLD.product_id AND user_id = OLD.user_id;
    END IF;
    RETURN OLD;
  END IF;
  RETURN NULL;
END;
$function$;

