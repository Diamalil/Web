CREATE OR REPLACE FUNCTION private.replace_feeku_business_data(
  p_user_id uuid,
  p_data jsonb,
  p_replace_existing boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_categories jsonb := coalesce(p_data->'categories','[]'::jsonb);
  v_products jsonb := coalesce(p_data->'products','[]'::jsonb);
  v_transactions jsonb := coalesce(p_data->'transactions','[]'::jsonb);
  v_profits jsonb := coalesce(p_data->'profits','[]'::jsonb);
  v_logs jsonb := coalesce(p_data->'activity_logs','[]'::jsonb);
  v_category_map jsonb := '{}'::jsonb;
  v_product_map jsonb := '{}'::jsonb;
  v_rec jsonb;
  v_item jsonb;
  v_old_id bigint;
  v_old_category_id bigint;
  v_category_id uuid;
  v_product_id uuid;
  v_transaction_id uuid;
  v_name text;
  v_description text;
  v_date date;
  v_direction public.transaction_direction;
  v_source public.transaction_source;
  v_amount numeric(18,2);
  v_stock numeric(18,3);
  v_sold numeric(18,3);
  v_quantity numeric(18,3);
  v_cost numeric(18,2);
  v_sale numeric(18,2);
  v_pricing_method public.product_pricing_method;
  v_pricing_value numeric(18,2);
  v_sku text;
  v_unit text;
  v_items jsonb;
  v_inserted_categories integer := 0;
  v_inserted_products integer := 0;
  v_inserted_transactions integer := 0;
  v_inserted_items integer := 0;
  v_inserted_profits integer := 0;
  v_inserted_logs integer := 0;
BEGIN
  IF p_user_id IS NULL OR NOT EXISTS (SELECT 1 FROM auth.users u WHERE u.id = p_user_id) THEN
    RAISE EXCEPTION 'Akun Auth tujuan tidak ditemukan' USING ERRCODE = 'P0002';
  END IF;
  IF jsonb_typeof(v_categories) <> 'array'
     OR jsonb_typeof(v_products) <> 'array'
     OR jsonb_typeof(v_transactions) <> 'array'
     OR jsonb_typeof(v_profits) <> 'array'
     OR jsonb_typeof(v_logs) <> 'array' THEN
    RAISE EXCEPTION 'Payload migrasi tidak valid' USING ERRCODE = '22023';
  END IF;
  IF jsonb_array_length(v_categories) + jsonb_array_length(v_products)
     + jsonb_array_length(v_transactions) + jsonb_array_length(v_profits)
     + jsonb_array_length(v_logs) > 10000 THEN
    RAISE EXCEPTION 'Data per akun melebihi batas 10.000 baris' USING ERRCODE = '22023';
  END IF;

  IF p_replace_existing THEN
    DELETE FROM public.transactions WHERE user_id = p_user_id;
    DELETE FROM public.profits WHERE user_id = p_user_id;
    DELETE FROM public.products WHERE user_id = p_user_id;
    DELETE FROM public.categories WHERE user_id = p_user_id;
    DELETE FROM public.activity_logs WHERE user_id = p_user_id;
  ELSE
    IF EXISTS (SELECT 1 FROM public.categories WHERE user_id=p_user_id)
       OR EXISTS (SELECT 1 FROM public.products WHERE user_id=p_user_id)
       OR EXISTS (SELECT 1 FROM public.transactions WHERE user_id=p_user_id)
       OR EXISTS (SELECT 1 FROM public.profits WHERE user_id=p_user_id)
       OR EXISTS (SELECT 1 FROM public.activity_logs WHERE user_id=p_user_id) THEN
      RAISE EXCEPTION 'Data PostgreSQL tujuan sudah berisi data; import otomatis dibatalkan untuk mencegah penimpaan' USING ERRCODE = '23505';
    END IF;
  END IF;

  FOR v_rec IN SELECT value FROM jsonb_array_elements(v_categories) LOOP
    v_old_id := nullif(v_rec->>'id','')::bigint;
    v_name := left(btrim(coalesce(v_rec->>'name','')),80);
    IF v_name = '' THEN
      RAISE EXCEPTION 'Nama kategori tidak valid' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.categories(user_id,name,description)
    VALUES (p_user_id,v_name,nullif(left(coalesce(v_rec->>'description',''),300),''))
    ON CONFLICT (user_id,name) DO UPDATE
      SET description = EXCLUDED.description
    RETURNING id INTO v_category_id;
    IF v_old_id IS NOT NULL THEN
      v_category_map := v_category_map || jsonb_build_object(v_old_id::text,v_category_id::text);
    END IF;
    v_inserted_categories := v_inserted_categories + 1;
  END LOOP;

  FOR v_rec IN SELECT value FROM jsonb_array_elements(v_products) LOOP
    v_old_id := nullif(v_rec->>'id','')::bigint;
    v_old_category_id := coalesce(nullif(v_rec->>'category_id','')::bigint, nullif(v_rec->>'categoryId','')::bigint);
    v_category_id := NULL;
    IF v_old_category_id IS NOT NULL THEN
      v_category_id := nullif(v_category_map->>v_old_category_id::text,'')::uuid;
    END IF;
    IF v_category_id IS NULL AND nullif(v_rec->>'category','') IS NOT NULL THEN
      SELECT c.id INTO v_category_id FROM public.categories c
       WHERE c.user_id=p_user_id AND lower(c.name)=lower(v_rec->>'category')
       LIMIT 1;
    END IF;
    IF v_category_id IS NULL THEN
      RAISE EXCEPTION 'Kategori produk tidak ditemukan saat migrasi' USING ERRCODE = '23503';
    END IF;

    v_name := left(btrim(coalesce(v_rec->>'name','')),150);
    IF v_name = '' THEN RAISE EXCEPTION 'Nama produk tidak valid' USING ERRCODE = '22023'; END IF;
    v_stock := coalesce(nullif(v_rec->>'stock_quantity','')::numeric, nullif(v_rec->>'stock','')::numeric, 0);
    v_cost := coalesce(nullif(v_rec->>'unit_cost','')::numeric,0);
    v_sale := coalesce(nullif(v_rec->>'sale_price','')::numeric,nullif(v_rec->>'price','')::numeric,0);
    v_pricing_value := coalesce(nullif(v_rec->>'pricing_value','')::numeric,0);
    v_pricing_method := CASE coalesce(v_rec->>'pricing_method','manual')
      WHEN 'markup' THEN 'markup'::public.product_pricing_method
      WHEN 'margin' THEN 'target_margin'::public.product_pricing_method
      WHEN 'target_margin' THEN 'target_margin'::public.product_pricing_method
      WHEN 'fixed' THEN 'fixed_profit'::public.product_pricing_method
      WHEN 'fixed_profit' THEN 'fixed_profit'::public.product_pricing_method
      ELSE 'manual'::public.product_pricing_method END;

    SELECT coalesce(sum(nullif(li.value->>'quantity','')::numeric),0)
      INTO v_sold
      FROM jsonb_array_elements(v_transactions) AS tx(value)
      CROSS JOIN LATERAL jsonb_array_elements(coalesce(tx.value->'items','[]'::jsonb)) AS li(value)
     WHERE nullif(li.value->>'product_id','') = coalesce(v_old_id::text,'');
    IF v_stock < 0 OR v_cost < 0 OR v_sale < 0 OR v_sold < 0 THEN
      RAISE EXCEPTION 'Nilai stok/harga produk tidak valid' USING ERRCODE = '22023';
    END IF;
    v_sku := nullif(v_rec->>'sku','');
    v_unit := left(coalesce(nullif(v_rec->>'unit_name',''),'pcs'),24);

    INSERT INTO public.products(
      user_id,category_id,name,sku,unit_name,stock_quantity,unit_cost,sale_price,
      pricing_method,pricing_value,is_active
    ) VALUES (
      p_user_id,v_category_id,v_name,v_sku,v_unit,v_stock+v_sold,v_cost,v_sale,
      v_pricing_method,v_pricing_value,coalesce(nullif(v_rec->>'is_active','')::boolean,true)
    )
    RETURNING id INTO v_product_id;
    IF v_old_id IS NOT NULL THEN
      v_product_map := v_product_map || jsonb_build_object(v_old_id::text,v_product_id::text);
    END IF;
    v_inserted_products := v_inserted_products + 1;
  END LOOP;

  FOR v_rec IN SELECT value FROM jsonb_array_elements(v_transactions) LOOP
    v_items := coalesce(v_rec->'items','[]'::jsonb);
    IF jsonb_typeof(v_items) <> 'array' THEN
      RAISE EXCEPTION 'Rincian transaksi tidak valid' USING ERRCODE = '22023';
    END IF;
    v_date := coalesce(nullif(v_rec->>'entry_date','')::date, nullif(v_rec->>'date','')::date);
    v_description := left(btrim(coalesce(v_rec->>'description','')),200);
    v_direction := coalesce(v_rec->>'direction',v_rec->>'type')::public.transaction_direction;
    IF v_date IS NULL OR v_description = '' THEN
      RAISE EXCEPTION 'Tanggal atau keterangan transaksi tidak valid' USING ERRCODE = '22023';
    END IF;
    v_source := CASE WHEN jsonb_array_length(v_items)>0 THEN 'catalog_sale'::public.transaction_source
                     ELSE 'manual'::public.transaction_source END;
    IF v_source = 'catalog_sale' AND v_direction <> 'Masuk' THEN
      RAISE EXCEPTION 'Penjualan katalog harus berupa transaksi Masuk' USING ERRCODE = '22023';
    END IF;

    IF v_source = 'manual' THEN
      v_amount := coalesce(nullif(v_rec->>'amount','')::numeric,0);
    ELSE
      v_amount := 0;
      FOR v_item IN SELECT value FROM jsonb_array_elements(v_items) LOOP
        v_quantity := coalesce(nullif(v_item->>'quantity','')::numeric,0);
        v_sale := coalesce(nullif(v_item->>'sale_price_snapshot','')::numeric,
                           nullif(v_item->>'unit_sale_price','')::numeric,
                           nullif(v_item->>'sale_price','')::numeric,0);
        IF v_quantity <= 0 OR v_sale <= 0 THEN
          RAISE EXCEPTION 'Jumlah atau harga snapshot produk tidak valid' USING ERRCODE = '22023';
        END IF;
        v_amount := v_amount + round(v_quantity*v_sale,2);
      END LOOP;
    END IF;
    IF v_amount <= 0 OR v_amount > 1000000000000 THEN
      RAISE EXCEPTION 'Nominal transaksi tidak valid' USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.transactions(user_id,entry_date,description,direction,amount,source)
    VALUES(p_user_id,v_date,v_description,v_direction,v_amount,v_source)
    RETURNING id INTO v_transaction_id;
    v_inserted_transactions := v_inserted_transactions + 1;

    IF v_source = 'catalog_sale' THEN
      FOR v_item IN SELECT value FROM jsonb_array_elements(v_items) LOOP
        v_old_id := nullif(v_item->>'product_id','')::bigint;
        v_product_id := CASE WHEN v_old_id IS NULL THEN NULL
                             ELSE nullif(v_product_map->>v_old_id::text,'')::uuid END;
        v_quantity := nullif(v_item->>'quantity','')::numeric;
        v_cost := coalesce(nullif(v_item->>'unit_cost_snapshot','')::numeric,
                           nullif(v_item->>'unit_cost','')::numeric,0);
        v_sale := coalesce(nullif(v_item->>'sale_price_snapshot','')::numeric,
                           nullif(v_item->>'unit_sale_price','')::numeric,
                           nullif(v_item->>'sale_price','')::numeric,0);
        v_name := left(btrim(coalesce(v_item->>'product_name_snapshot',v_item->>'product_name','Produk terhapus')),150);
        v_sku := nullif(coalesce(v_item->>'sku_snapshot',v_item->>'sku',''),'');
        IF v_quantity <= 0 OR v_cost < 0 OR v_sale <= 0 OR v_name = '' THEN
          RAISE EXCEPTION 'Snapshot item penjualan tidak valid' USING ERRCODE = '22023';
        END IF;
        INSERT INTO public.transaction_items(
          user_id,transaction_id,product_id,product_name_snapshot,sku_snapshot,
          quantity,unit_cost_snapshot,sale_price_snapshot
        ) VALUES(p_user_id,v_transaction_id,v_product_id,v_name,v_sku,v_quantity,v_cost,v_sale);
        v_inserted_items := v_inserted_items + 1;
      END LOOP;
    END IF;
  END LOOP;

  -- Margin catalog-sale profits are generated by the existing database trigger.
  FOR v_rec IN SELECT value FROM jsonb_array_elements(v_profits) LOOP
    IF nullif(v_rec->>'source_transaction_id','') IS NOT NULL
       OR coalesce(v_rec->>'source','manual') = 'transaction_margin' THEN
      CONTINUE;
    END IF;
    v_date := coalesce(nullif(v_rec->>'entry_date','')::date, nullif(v_rec->>'date','')::date);
    v_direction := coalesce(v_rec->>'direction',v_rec->>'type')::public.transaction_direction;
    v_description := left(btrim(coalesce(v_rec->>'description','')),200);
    v_amount := coalesce(nullif(v_rec->>'amount','')::numeric,0);
    IF v_date IS NULL OR v_description='' OR v_amount<=0 THEN
      RAISE EXCEPTION 'Catatan keuntungan manual tidak valid' USING ERRCODE = '22023';
    END IF;
    INSERT INTO public.profits(user_id,entry_date,description,direction,amount,source)
    VALUES(p_user_id,v_date,v_description,v_direction,v_amount,'manual');
    v_inserted_profits := v_inserted_profits + 1;
  END LOOP;

  FOR v_rec IN SELECT value FROM jsonb_array_elements(v_logs) LOOP
    IF nullif(v_rec->>'action','') IS NULL OR nullif(v_rec->>'entity_type','') IS NULL THEN
      CONTINUE;
    END IF;
    INSERT INTO public.activity_logs(user_id,actor_user_id,action,entity_type,entity_id,metadata,created_at)
    VALUES(
      p_user_id,
      CASE WHEN nullif(v_rec->>'actor_user_id','') IS NULL THEN NULL ELSE p_user_id END,
      left(v_rec->>'action',100),
      left(v_rec->>'entity_type',80),
      nullif(v_rec->>'entity_id',''),
      CASE WHEN jsonb_typeof(v_rec->'metadata')='object' THEN v_rec->'metadata' ELSE '{}'::jsonb END,
      coalesce(nullif(v_rec->>'created_at','')::timestamptz,now())
    );
    v_inserted_logs := v_inserted_logs + 1;
  END LOOP;

  RETURN jsonb_build_object(
    'categories',v_inserted_categories,
    'products',v_inserted_products,
    'transactions',v_inserted_transactions,
    'transaction_items',v_inserted_items,
    'manual_profits',v_inserted_profits,
    'activity_logs',v_inserted_logs
  );
END;
$function$;

